#!/usr/bin/env python3
"""Import fixed-voice WAVs and generate verified immutable firmware cue assets.

Render with the configured TTS provider outside this tool, then import each
WAV. Credentials never belong in generated files. The firmware uses the same
OTA flash image for atomic cue installation and rollback; no new partitions.
"""
import argparse
import hashlib
import json
import os
import wave
import zlib
from pathlib import Path

PHRASES = {'listening': 'Слушаю.', 'processing': 'Обрабатываю.', 'offline': 'Нет связи.'}


def import_wav(source, output, name, model, voice):
    with wave.open(str(source), 'rb') as wav:
        if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getcomptype()) != (1, 2, 24000, 'NONE'):
            raise ValueError('cue must be 24 kHz mono PCM16')
        frames = wav.getnframes()
        pcm = wav.readframes(frames)
        if not 0 < frames <= 120000 or len(pcm) != frames * 2:
            raise ValueError('cue must contain complete PCM and last at most five seconds')
    output.mkdir(parents=True, exist_ok=True)
    metadata = dict(text=PHRASES[name], model=model, voice=voice, sample_rate=24000,
                    channels=1, bits_per_sample=16, size=len(pcm), sha256=hashlib.sha256(pcm).hexdigest())
    # Stage before replacing; build validates both SHA and format so an
    # interrupted pair update cannot silently produce a new firmware.
    for suffix, data in [('pcm', pcm), ('json', (json.dumps(metadata, ensure_ascii=False, indent=2)+'\n').encode())]:
        target = output / f'voice-{name}.{suffix}'
        part = target.with_suffix(target.suffix+'.part')
        with part.open('wb') as f:
            f.write(data); f.flush(); os.fsync(f.fileno())
        os.replace(part, target)


def manifest(assets, header):
    lines = ['/* Generated by deploy/firmware/prepare-static-cues.py; PCM integrity. */']
    for name, phrase in PHRASES.items():
        pcm = (assets / f'voice-{name}.pcm').read_bytes()
        meta = json.loads((assets / f'voice-{name}.json').read_text())
        if (meta['sample_rate'], meta['channels'], meta['bits_per_sample'], meta['text']) != (24000, 1, 16, phrase):
            raise ValueError(f'invalid metadata for {name}')
        if not 0 < len(pcm) <= 240000 or len(pcm) % 2 or hashlib.sha256(pcm).hexdigest() != meta['sha256']:
            raise ValueError(f'invalid PCM/hash for {name}')
        if meta.get('size', len(pcm)) != len(pcm):
            raise ValueError(f'invalid length for {name}')
        lines.append(f'#define VOICE_{name.upper()}_CRC 0x{zlib.crc32(pcm):08x}u')
    text = '\n'.join(lines)+'\n'
    if not header.exists() or header.read_text() != text:
        header.write_text(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assets', type=Path, default=Path('firmware/assets'))
    parser.add_argument('--header', type=Path, default=Path('firmware/include/voice_static_cues_manifest.h'))
    parser.add_argument('--name', choices=PHRASES)
    parser.add_argument('--source', type=Path)
    parser.add_argument('--model')
    parser.add_argument('--voice')
    args = parser.parse_args()
    if args.source:
        if not all((args.name, args.model, args.voice)):
            parser.error('--source requires --name, --model and --voice')
        import_wav(args.source, args.assets, args.name, args.model, args.voice)
    manifest(args.assets, args.header)
